"""Tests for tools/release_check.py and lint rule L16 against a fake endpoint.

The check must establish that the endpoint is MHSB's (PP1-N1): a third-party
host with a valid certificate fails, a static 401 fails, and a fake MHSB
endpoint answering an authenticated initialize with the recorded serverInfo
passes. The fake endpoint is a local HTTPS server with a throwaway self-signed
certificate generated by openssl at test time; no key material is committed
and no test reaches the network.
"""

