# Lint rule L16 (release only)


@pytest.fixture()
def repo(tmp_path: Path) -> Path:
    target = tmp_path / "repo"
    shutil.copytree(ROOT, target, ignore=shutil.ignore_patterns(".git", "__pycache__", ".pytest_cache"))
    return target


def promote_operations(root: Path, listing: bool) -> None:
    path = root / "catalog" / "manifest.yaml"
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    for entry in data["plugins"]:
        if entry["name"] == "mhsb-operations":
            entry["tier"] = "ga"
    if listing:
        data["defaults"]["connector_listing"] = {
            "privacy_policy_url": "https://example.com/privacy",
            "terms_of_service_url": "https://example.com/terms"}
    path.write_text(yaml.safe_dump(data, sort_keys=False), encoding="utf-8")
    assert gen_manifest.main(["--root", str(root)]) == 0


def l16(root: Path, release: bool = True) -> list[lint.Finding]:
    return [f for f in lint.run(root, release=release) if f.rule == "L16"]


def fake_check(ok: bool):
    def check(url: str, timeout: float = 0, context: object = None) -> release_check.CheckResult:
        return release_check.CheckResult(url, ok, "mcp", "fake")
    return check


def test_l16_ga_connector_failing_check_fails_release(repo: Path, monkeypatch) -> None:
    promote_operations(repo, listing=True)
    monkeypatch.setattr(release_check, "check_url", fake_check(False))
    findings = l16(repo)
    assert [f.path for f in findings] == ["plugins/mhsb-operations/.mcp.json"]
    assert lint.main(["--root", str(repo), "--release"]) == 1


def test_l16_ga_connector_live_endpoint_passes(repo: Path, monkeypatch, endpoint) -> None:
    url, cafile = endpoint("auth")
    promote_operations(repo, listing=True)
    real = release_check.check_url
    monkeypatch.setattr(release_check, "check_url",
                        lambda _url, timeout=5, context=None: real(url, timeout, trusting(cafile)))
    assert l16(repo) == []


def test_l16_ga_connector_without_listing_urls_fails(repo: Path, monkeypatch) -> None:
    promote_operations(repo, listing=False)
    monkeypatch.setattr(release_check, "check_url", fake_check(True))
    messages = sorted(f.message for f in l16(repo))
    assert messages == ["connector plugin at tier ga lacks privacyPolicyUrl",
                        "connector plugin at tier ga lacks termsOfServiceUrl"]


def test_l16_not_run_in_development(repo: Path, monkeypatch) -> None:
    promote_operations(repo, listing=False)
    monkeypatch.setattr(release_check, "check_url", fake_check(False))
    assert l16(repo, release=False) == []


def test_l16_connector_plugins_held_at_pilot_need_no_endpoint(monkeypatch) -> None:
    """The repository as committed: no network call when no connector plugin is ga."""
    def refuse(*_args: object, **_kwargs: object) -> release_check.CheckResult:
        raise AssertionError("release check called for a connector no ga plugin uses")
    monkeypatch.setattr(release_check, "check_url", refuse)
    assert l16(ROOT) == []
