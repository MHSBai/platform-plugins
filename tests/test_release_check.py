def make_cert(directory: Path, name: str) -> tuple[Path, Path]:
    cert, key = directory / f"{name}.crt", directory / f"{name}.key"
    subprocess.run(
        ["openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-days", "1",
         "-keyout", str(key), "-out", str(cert), "-subj", f"/CN={name}",
         "-addext", f"subjectAltName=DNS:{name}"],
        check=True, capture_output=True,
    )
    return cert, key


TOKEN = "release-check-test-token"
LOCAL = (ipaddress.ip_network("127.0.0.0/8"), ipaddress.ip_network("::1/128"))
EXPECTED = release_check.Expected("MHSB firm connector", "0.4.0", networks=LOCAL)


def init_result(name: str, version: str) -> dict:
    return {"jsonrpc": "2.0", "id": 1,
            "result": {"protocolVersion": release_check.MCP_PROTOCOL_VERSION, "capabilities": {},
                       "serverInfo": {"name": name, "version": version}}}


CHALLENGE = {"WWW-Authenticate": 'Bearer resource_metadata="https://localhost/.well-known/'
                                 'oauth-protected-resource"'}


class Handler(BaseHTTPRequestHandler):
    mode = "mhsb"

    def log_message(self, *args: object) -> None:  # silence the test output
        pass

    def do_POST(self) -> None:  # noqa: N802
        length = int(self.headers.get("Content-Length", "0"))
        request = json.loads(self.rfile.read(length))
        assert request["method"] == "initialize"
        mode = type(self).mode
        signed_in = self.headers.get("Authorization") == f"Bearer {TOKEN}"
        if mode in ("mhsb", "mhsb-sse"):
            # A fake MHSB endpoint: initialize only for a signed-in client, as the service does.
            if not signed_in:
                self._send(401, "application/json", '{"error": "unauthorized"}', CHALLENGE)
                return
            result = json.dumps(init_result("MHSB firm connector", "0.4.0"))
            if mode == "mhsb":
                self._send(200, "application/json", result)
            else:
                self._send(200, "text/event-stream", f"event: message\ndata: {result}\n\n")
        elif mode == "other":
            # A third-party MCP server on a host with a valid certificate.
            self._send(200, "application/json", json.dumps(init_result("hosting-platform-demo", "1.0.0")))
        elif mode == "auth":
            # A static 401 with an empty JSON body: what any host can return.
            self._send(401, "application/json", "{}", CHALLENGE)
        elif mode == "html":
            self._send(200, "text/html", "<html><body>Parked domain</body></html>")
        else:
            self._send(404, "text/plain", "not found")

    def _send(self, status: int, ctype: str, body: str, extra: dict[str, str] | None = None) -> None:
        data = body.encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(data)))
        for key, value in (extra or {}).items():
            self.send_header(key, value)
        self.end_headers()
        self.wfile.write(data)


@pytest.fixture()
def endpoint(tmp_path: Path):
    """Yield a factory: endpoint(mode, cert_name) -> (url, cafile)."""
    servers: list[ThreadingHTTPServer] = []

    def start(mode: str, cert_name: str = "localhost") -> tuple[str, Path]:
        cert, key = make_cert(tmp_path, cert_name)
        handler = type(f"Handler_{mode}", (Handler,), {"mode": mode})
        server = ThreadingHTTPServer(("127.0.0.1", 0), handler)
        context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        context.load_cert_chain(cert, key)
        server.socket = context.wrap_socket(server.socket, server_side=True)
        threading.Thread(target=server.serve_forever, daemon=True).start()
        servers.append(server)
        return f"https://localhost:{server.server_address[1]}/firm", cert

    yield start
    for server in servers:
        server.shutdown()
        server.server_close()


def trusting(cafile: Path) -> ssl.SSLContext:
    return ssl.create_default_context(cafile=str(cafile))


def check(url: str, cafile: Path, expected: release_check.Expected = EXPECTED,
          token: str | None = TOKEN) -> release_check.CheckResult:
    return release_check.check_url(url, expected, timeout=5, context=trusting(cafile), token=token)


@pytest.mark.parametrize("mode", ["mhsb", "mhsb-sse"])
def test_fake_mhsb_endpoint_answering_initialize_passes(endpoint, mode: str) -> None:
    url, cafile = endpoint(mode)
    result = check(url, cafile)
    assert result.ok, result.render()
    assert "MHSB firm connector 0.4.0" in result.detail


def test_static_401_fails(endpoint) -> None:
    """A 401 with a Bearer challenge and an empty body is not proof of life (PP1-N1)."""
    url, cafile = endpoint("auth")
    result = check(url, cafile)
    assert not result.ok and result.step == "identity", result.render()
    assert "HTTP 401" in result.detail


