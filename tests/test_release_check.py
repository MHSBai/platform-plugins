"""Tests for tools/release_check.py and lint rule L16 against a fake endpoint.

The fake endpoint is a local HTTPS server with a throwaway self-signed
certificate generated by openssl at test time; no key material is committed
and no test reaches the network.
"""

from __future__ import annotations

import json
