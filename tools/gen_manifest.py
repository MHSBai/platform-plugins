#!/usr/bin/env python3
"""Generate derived files from catalog/manifest.yaml.

Outputs, all derived and never edited by hand:

* .claude-plugin/marketplace.json (general availability plugins only)
* plugins/<name>/.claude-plugin/plugin.json for every plugin
* plugins/<name>/.mcp.json for every plugin that bundles a connector
* catalog/counts.md, the command counts table per supported combination
* docs/catalog.md, the human-readable catalog

Usage:
    python tools/gen_manifest.py            write every output
    python tools/gen_manifest.py --check    exit 1 if any output differs from disk
    python tools/gen_manifest.py --counts   print the counts table to stdout
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import OrderedDict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from manifest_lib import Manifest, load_manifest  # noqa: E402

GENERATED_NOTE = "Generated by tools/gen_manifest.py from catalog/manifest.yaml. Do not edit by hand."


def _json(data: object) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def plugin_json(manifest: Manifest, name: str) -> dict[str, object]:
    plugin = manifest.plugin(name)
    defaults = manifest.defaults
    return OrderedDict([
        ("name", plugin.name),
        ("version", defaults["version"]),
        ("description", plugin.description),
        ("author", defaults["author"]),
        ("homepage", defaults["homepage"]),
        ("repository", defaults["repository"]),
        ("license", plugin.license_id),
        ("keywords", list(dict.fromkeys(["legal", "law-firm", plugin.kind, plugin.category]))),
    ])


def mcp_json(manifest: Manifest, name: str) -> dict[str, object] | None:
    plugin = manifest.plugin(name)
    if plugin.mcp is None:
        return None
    server = f"mhsb-{plugin.mcp}"
    return {"mcpServers": {server: {"type": "http", "url": manifest.connectors[plugin.mcp]}}}


def marketplace_json(manifest: Manifest) -> dict[str, object]:
    entries = []
    for plugin in manifest.plugins:
        if plugin.tier != "ga":
            continue
        entries.append(OrderedDict([
            ("name", plugin.name),
            ("source", f"./{manifest.plugin_root}/{plugin.name}"),
            ("description", plugin.description),
            ("category", plugin.category),
        ]))
    market = manifest.marketplace
    return OrderedDict([
        ("name", market["name"]),
        ("description", " ".join(str(market["description"]).split())),
        ("version", manifest.defaults["version"]),
        ("owner", market["owner"]),
        ("plugins", entries),
    ])


def counts_rows(manifest: Manifest) -> list[dict[str, object]]:
    """One row per (family, platform) with the command count per member."""
    groups: "OrderedDict[tuple[str, str], list[int]]" = OrderedDict()
    breakdown: dict[tuple[str, str], str] = {}
    for combo in manifest.combinations():
        platforms = [n for n in combo.plugins if manifest.plugin(n).kind == "platform"]
        platform = platforms[0] if platforms else "none"
        key = (combo.family, platform)
        total = len(manifest.commands_in(combo))
        groups.setdefault(key, []).append(total)
        parts = []
        for kind in ("core", "operations", "platform", "practice"):
            members = [n for n in combo.plugins if manifest.plugin(n).kind == kind]
            if members:
                parts.append(str(sum(len(manifest.plugin(n).commands) for n in members)))
        breakdown.setdefault(key, " + ".join(parts))
    rows = []
    for (family, platform), totals in groups.items():
        rows.append({
            "family": family, "platform": platform, "variants": len(totals),
            "breakdown": breakdown[(family, platform)],
            "min": min(totals), "max": max(totals),
        })
    return rows


def counts_markdown(manifest: Manifest) -> str:
    rows = counts_rows(manifest)
    combos = manifest.combinations()
    overall = max(len(manifest.commands_in(c)) for c in combos)
    cap = manifest.limits["max_commands_per_combination"]
    lines = [
        "# Command counts per supported combination",
        "",
        GENERATED_NOTE,
        "",
        "Breakdown order: core + operations + platform + practice packs. Practice packs add no commands.",
        "",
        "| Combination | Platform | Variants | Breakdown | Commands (min) | Commands (max) |",
        "|---|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| {row['family']} | {row['platform']} | {row['variants']} | {row['breakdown']} "
            f"| {row['min']} | {row['max']} |"
        )
    lines += [
        "",
        f"Supported combinations enumerated: {len(combos)}.",
        f"Maximum commands in any combination: {overall}.",
        f"Lint cap: {cap}. Design figure: {manifest.limits['design_commands_per_combination']}.",
        "",
        "| Plugin | Kind | Tier | Commands |",
        "|---|---|---|---|",
    ]
    for plugin in manifest.plugins:
        lines.append(f"| {plugin.name} | {plugin.kind} | {plugin.tier} | {len(plugin.commands)} |")
    lines.append("")
    return "\n".join(lines)


def catalog_markdown(manifest: Manifest) -> str:
    lines = [
        "# Catalog",
        "",
        GENERATED_NOTE,
        "",
        "Commands run as `/<plugin>:<command>` in Claude Code and Cowork; in chat they load as skills"
        " selected from plain language. Pilot and hidden plugins are present in this repository and"
        " excluded from the marketplace listing.",
        "",
        "## Plugins",
        "",
        "| Plugin | Kind | Tier | Listed | License | Connector | Commands |",
        "|---|---|---|---|---|---|---|",
    ]
    for p in manifest.plugins:
        connector = manifest.connectors[p.mcp] if p.mcp else "none"
        listed = "yes" if p.tier == "ga" else "no"
        lines.append(f"| {p.name} | {p.kind} | {p.tier} | {listed} | {p.license_id} | {connector} "
                     f"| {len(p.commands)} |")
    lines += ["", "## Commands", ""]
    for p in manifest.plugins:
        if not p.commands:
            continue
        lines += [f"### {p.name}", "",
                  "| Command | Register | Connector | Promise | Trigger phrases |",
                  "|---|---|---|---|---|"]
        for c in p.commands:
            triggers = "; ".join(f"\"{t}\"" for t in c.triggers)
            lines.append(f"| /{c.name} | {c.register} | {c.connector} | {c.promise} | {triggers} |")
        lines.append("")
    lines += ["## Practice packs", "", "| Pack | Practice | Tier |", "|---|---|---|"]
    for p in manifest.by_kind("practice"):
        lines.append(f"| {p.name} | {p.practice} | {p.tier} |")
    lines += ["", "## Supported combinations", ""]
    for rule in manifest.raw["combinations"]:
        lines.append(f"* `{rule['id']}`: {' '.join(str(rule['description']).split())}")
    lines += ["", "## Counts", ""]
    body = counts_markdown(manifest).split("\n")
    start = next(i for i, line in enumerate(body) if line.startswith("Breakdown order"))
    lines += body[start:]
    return "\n".join(lines).rstrip("\n") + "\n"


def outputs(manifest: Manifest) -> dict[Path, str]:
    files: dict[Path, str] = {
        Path(".claude-plugin/marketplace.json"): _json(marketplace_json(manifest)),
        Path("catalog/counts.md"): counts_markdown(manifest),
        Path("docs/catalog.md"): catalog_markdown(manifest),
    }
    for plugin in manifest.plugins:
        base = Path(manifest.plugin_root) / plugin.name
        files[base / ".claude-plugin/plugin.json"] = _json(plugin_json(manifest, plugin.name))
        mcp = mcp_json(manifest, plugin.name)
        if mcp is not None:
            files[base / ".mcp.json"] = _json(mcp)
    return files


def check(root: Path, manifest: Manifest) -> list[str]:
    drift = []
    for rel, content in outputs(manifest).items():
        path = root / rel
        if not path.exists():
            drift.append(f"missing: {rel}")
        elif path.read_text(encoding="utf-8") != content:
            drift.append(f"differs: {rel}")
    for plugin in manifest.plugins:
        mcp = root / manifest.plugin_root / plugin.name / ".mcp.json"
        if plugin.mcp is None and mcp.exists():
            drift.append(f"unexpected: {mcp.relative_to(root)}")
    return drift


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="report drift and exit 1 if any")
    mode.add_argument("--counts", action="store_true", help="print the counts table")
    args = parser.parse_args(argv)
    manifest = load_manifest(args.root)
    if args.counts:
        sys.stdout.write(counts_markdown(manifest))
        return 0
    if args.check:
        drift = check(args.root, manifest)
        for line in drift:
            print(line)
        print("generated files current" if not drift else f"{len(drift)} generated file(s) out of date")
        return 1 if drift else 0
    for rel, content in outputs(manifest).items():
        path = args.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
